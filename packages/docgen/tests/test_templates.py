"""Every bundled template must render, with data and without it.

The failure this guards against is specific and expensive: a template that
works in a demo, where every field happens to be filled, and breaks on the
first real upload, where half the fields are empty because the photo was taken
at an angle. Partial extraction is the normal case, not the exception, so both
paths are tested for every template.

The templates are generated by scripts/build_templates.py. These tests assert
on the committed .docx files, so a hand-edit that breaks one is caught even if
nobody re-runs the generator.
"""

from __future__ import annotations

import io

import pytest
from docx import Document

from packages.docgen.engine import analyze, render_docx
from packages.schema.models import (
    Education,
    ExtractionResult,
    FieldValue,
    IdentityDocument,
    Subject,
)

TEMPLATE_DIR = __import__("pathlib").Path(
    __file__).resolve().parents[1] / "templates"

EXPECTED = [
    "ish_arizasi.docx",
    "malumotnoma.docx",
    "mehnat_shartnomasi.docx",
    "otm_arizasi.docx",
    "ishonchnoma.docx",
    "diplom_ilovasi.docx",
]

EXTRA = {
    "salary": 7500000,
    "position": "dasturchi",
    "employer": "«Namuna» MChJ",
    "university": "TATU",
    "attorney_number": "12/3",
}


def template_bytes(name: str) -> bytes:
    return (TEMPLATE_DIR / name).read_bytes()


def empty_result() -> ExtractionResult:
    r = ExtractionResult(job_id="empty")
    r.documents.append(IdentityDocument())
    r.education = Education()
    return r


